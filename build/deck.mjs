// The Geo deck: every card, where its shape comes from, and how well known it is.
//
// Each card is [id, source, name, tier, extra?]
//   id      stable key for saved progress — never change or reuse one
//   source  where the shape comes from in Natural Earth:
//             c:ISO3      admin-0 countries (50m), "+"-joined to merge several
//             m:Name      marine areas (10m): oceans, seas, gulfs, bays, straits…
//             r:NAME      geographic regions (10m): islands, ranges, deserts…
//             l:Name      lakes (50m)
//             x:lon,lat;… a hand-drawn outline (for water only; the coast clips it)
//             o:lon,lat,r a circle of r degrees
//   tier    1 = very well known … 4 = for the keen; drives "Best known first"
//   extra   countries: { cap, note, at } — capital, an optional note, and the
//           capital's name in Natural Earth's populated places when it differs,
//           or pt: [lon, lat] for a capital Natural Earth doesn't have
//           other cards: { note } — a short line shown under the name
//
